#!/usr/bin/env bash
# Builds the WebAssembly module and copies it into the npm package and Go module.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"

cargo build --quiet --manifest-path "$root/Cargo.toml" -p appsync-scalars-wasm \
  --target wasm32-unknown-unknown --profile wasm-release
wasm="$root/target/wasm32-unknown-unknown/wasm-release/appsync_scalars_wasm.wasm"

cp "$wasm" "$root/bindings/go/appsync_scalars.wasm"

# The text stays on short lines because package scanners read one very long line as minified code.
{
  printf '// Generated by scripts/build-wasm.sh. Do not edit.\n'
  printf '// The WebAssembly module built from crates/appsync-scalars-wasm, as base64.\n'
  printf 'export const WASM_BASE64 = [\n'
  { base64 < "$wasm" | tr -d '\n' | fold -w 76; echo; } | sed 's/.*/  "&",/'
  printf '].join("");\n'
} > "$root/bindings/js/wasm.generated.js"
